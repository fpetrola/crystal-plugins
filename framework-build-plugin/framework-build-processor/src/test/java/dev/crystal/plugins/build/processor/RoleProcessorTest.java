package dev.crystal.plugins.build.processor;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import javax.tools.Diagnostic;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.SimpleJavaFileObject;
import javax.tools.StandardJavaFileManager;
import javax.tools.ToolProvider;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class RoleProcessorTest {

    @TempDir
    Path out;

    private static final String ROLE = """
            package app;
            @dev.crystal.plugins.api.RoleInterface
            public interface Exporter { String format(); }
            """;

    /** A sub-interface: the role annotation is inherited through super-interfaces. */
    private static final String SUB_ROLE = """
            package app;
            public interface StreamingExporter extends Exporter { }
            """;

    @Test
    void generatesIndexServicesAndMetadata() throws IOException {
        Result result = compile(Map.of(
                "app.Exporter", ROLE,
                "app.StreamingExporter", SUB_ROLE,
                "p.Csv", """
                        package p;
                        public class Csv implements app.Exporter { public String format() { return "csv"; } }
                        """,
                "p.Outer", """
                        package p;
                        import dev.crystal.plugins.api.*;
                        public class Outer {
                            @Replaces("legacy-json") @Needs({"zlib", "fonts"})
                            public static class Json extends Base implements app.StreamingExporter, HasLifecycle {
                                @jakarta.inject.Inject public Json(Helper h) { }
                                public String format() { return "json"; }
                            }
                            public abstract static class Base { }
                            public static class Helper { }
                        }
                        """));
        assertTrue(result.errors().isEmpty(), result.errors().toString());

        assertEquals(List.of("# Generated by crystal-plugins (framework-build-processor)", "p.Csv", "p.Outer$Json"),
                Files.readAllLines(out.resolve("META-INF/extensions.idx")));
        // Json can only be built through its @Inject constructor: ServiceLoader could not instantiate it.
        assertEquals(List.of("p.Csv"), Files.readAllLines(out.resolve("META-INF/services/app.Exporter")));

        String json = Files.readString(out.resolve("META-INF/plugin-metadata.json"));
        assertEquals("""
                {
                  "format": 1,
                  "extensions": [
                    {
                      "class": "p.Csv",
                      "roles": ["app.Exporter"],
                      "replaces": [],
                      "needs": [],
                      "lifecycle": false
                    },
                    {
                      "class": "p.Outer$Json",
                      "roles": ["app.Exporter"],
                      "replaces": ["legacy-json"],
                      "needs": ["fonts", "zlib"],
                      "lifecycle": true
                    }
                  ],
                  "definesRoles": ["app.Exporter"]
                }
                """, json);
    }

    @Test
    void anApiModuleOnlyGetsItsRolesIndexed() throws IOException {
        Result result = compile(Map.of("app.Exporter", ROLE, "app.StreamingExporter", SUB_ROLE));
        assertTrue(result.errors().isEmpty(), result.errors().toString());
        assertFalse(Files.exists(out.resolve("META-INF/plugin-metadata.json")), "API modules are not plugins");
        assertFalse(Files.exists(out.resolve("META-INF/extensions.idx")));
        assertEquals(List.of("# Generated by crystal-plugins (framework-build-processor)", "app.Exporter"),
                Files.readAllLines(out.resolve("META-INF/crystal/roles.idx")),
                "only interfaces carrying @RoleInterface themselves");
    }

    @Test
    void roleImplementationsTheFrameworkCannotBuildAreNotExtensions() throws IOException {
        Result result = compile(Map.of(
                "app.Exporter", ROLE,
                "p.Real", """
                        package p;
                        public class Real implements app.Exporter { public String format() { return "real"; } }
                        """,
                "p.Hidden", """
                        package p;
                        class Hidden implements app.Exporter { public String format() { return ""; } }
                        """,
                "p.Tuned", """
                        package p;
                        public class Tuned implements app.Exporter {
                            private final int depth;
                            public Tuned(int depth) { this.depth = depth; }
                            public String format() { return "tuned" + depth; }
                        }
                        """,
                "p.Decorator", """
                        package p;
                        public class Decorator implements app.Exporter {
                            private final app.Exporter inner;
                            public Decorator(app.Exporter inner) { this.inner = inner; }
                            public String format() { return "[" + inner.format() + "]"; }
                        }
                        """,
                "p.Holder", """
                        package p;
                        public class Holder {
                            public class Inner implements app.Exporter { public String format() { return ""; } }
                        }
                        """));
        assertTrue(result.errors().isEmpty(), result.errors().toString());
        assertEquals(List.of("# Generated by crystal-plugins (framework-build-processor)", "p.Real"),
                Files.readAllLines(out.resolve("META-INF/extensions.idx")));

        String notes = String.join("\n", result.notes());
        assertTrue(notes.contains("Tuned implements [app.Exporter] but is not an extension"), notes);
        assertTrue(notes.contains("Decorator implements [app.Exporter] but is not an extension"), notes);
        assertFalse(notes.contains("Hidden"), "non-public classes are clearly internal: " + notes);
    }

    @Test
    void contradictionsAreErrors() {
        Result result = compile(Map.of(
                "app.Exporter", ROLE,
                "p.Hidden", """
                        package p;
                        class Hidden implements app.Exporter {
                            @jakarta.inject.Inject Hidden() { }
                            public String format() { return ""; }
                        }
                        """,
                "p.Holder", """
                        package p;
                        public class Holder {
                            public class Inner implements app.Exporter {
                                @jakarta.inject.Inject public Inner() { }
                                public String format() { return ""; }
                            }
                        }
                        """,
                "p.Twice", """
                        package p;
                        public class Twice implements app.Exporter {
                            @jakarta.inject.Inject public Twice() { }
                            @jakarta.inject.Inject public Twice(String s) { }
                            public String format() { return ""; }
                        }
                        """,
                "p.Tuned", """
                        package p;
                        @dev.crystal.plugins.api.Replaces("x")
                        public class Tuned implements app.Exporter {
                            public Tuned(int depth) { }
                            public String format() { return ""; }
                        }
                        """,
                "p.Stray", """
                        package p;
                        @dev.crystal.plugins.api.Needs("x") public class Stray { }
                        """,
                "p.NotAnInterface", """
                        package p;
                        @dev.crystal.plugins.api.RoleInterface public class NotAnInterface { }
                        """));
        String errors = String.join("\n", result.errors());
        assertTrue(errors.contains("Hidden has an @Inject constructor but cannot be an extension: it is not public"),
                errors);
        assertTrue(errors.contains("Inner has an @Inject constructor but cannot be an extension: it is an inner"),
                errors);
        assertTrue(errors.contains("more than one constructor is annotated with @Inject"), errors);
        assertTrue(errors.contains("@Replaces/@Needs only apply to extensions, and Tuned is not one"), errors);
        assertTrue(errors.contains("@Replaces/@Needs only apply to extensions, and Stray is not one"), errors);
        assertTrue(errors.contains("@RoleInterface can only be placed on an interface"), errors);
    }

    @Test
    void guicesOwnInjectAnnotationMakesAnExtension() throws IOException {
        Result result = compile(Map.of(
                "app.Exporter", ROLE,
                "com.google.inject.Inject", """
                        package com.google.inject;
                        @java.lang.annotation.Retention(java.lang.annotation.RetentionPolicy.RUNTIME)
                        public @interface Inject { }
                        """,
                "p.Guiced", """
                        package p;
                        public class Guiced implements app.Exporter {
                            @com.google.inject.Inject public Guiced(String name) { }
                            public String format() { return "guiced"; }
                        }
                        """));
        assertTrue(result.errors().isEmpty(), result.errors().toString());
        assertEquals(List.of("# Generated by crystal-plugins (framework-build-processor)", "p.Guiced"),
                Files.readAllLines(out.resolve("META-INF/extensions.idx")));
    }

    @Test
    void coexistsWithPf4jsOwnProcessor() throws IOException {
        // A host application or its tests: framework-runtime brings pf4j, whose @Extension processor always
        // writes META-INF/extensions.idx first. Ours must not break the compilation over it.
        Result result = compile(Map.of(
                "app.Exporter", ROLE,
                "p.Csv", """
                        package p;
                        public class Csv implements app.Exporter { public String format() { return "csv"; } }
                        """), new org.pf4j.processor.ExtensionAnnotationProcessor(), new RoleProcessor());

        assertTrue(result.errors().isEmpty(), result.errors().toString());
        String warnings = String.join("\n", result.warnings());
        assertTrue(warnings.contains("META-INF/extensions.idx was already written") && warnings.contains("pf4j"),
                warnings);
        assertEquals(List.of("p.Csv"), Files.readAllLines(out.resolve("META-INF/services/app.Exporter")),
                "services and metadata are still generated");
        assertTrue(Files.exists(out.resolve("META-INF/plugin-metadata.json")));
    }

    @Test
    void answersGoIntoTheMetadataPerRole() throws IOException {
        Result result = compile(Map.of(
                "dev.SnapshotFile", "package dev; @dev.crystal.plugins.api.RoleInterface public interface SnapshotFile { }",
                "dev.Machine", "package dev; @dev.crystal.plugins.api.RoleInterface public interface Machine { }",
                "dev.Tape", """
                        package dev;
                        @dev.crystal.plugins.api.Answers({"tzx", "tap"})
                        public class Tape implements SnapshotFile { }
                        """,
                "dev.Pentagon", """
                        package dev;
                        @dev.crystal.plugins.api.Answers(value = "Pentagon 128", role = Machine.class)
                        @dev.crystal.plugins.api.Answers(value = "pent", role = SnapshotFile.class)
                        public class Pentagon implements Machine, SnapshotFile { }
                        """,
                "dev.Wrong", """
                        package dev;
                        @dev.crystal.plugins.api.Answers(value = "x", role = Machine.class)
                        public class Wrong implements SnapshotFile { }
                        """));
        assertEquals(1, result.errors().size(), result.errors().toString());
        assertTrue(result.errors().get(0).contains("dev.Machine"), result.errors().get(0));
        String json = Files.readString(out.resolve(METADATA)).replaceAll("\\s+", "");
        assertTrue(json.contains("\"answers\":{\"dev.SnapshotFile\":[\"tap\",\"tzx\"]}"), json);
        assertTrue(json.contains("\"answers\":{\"dev.Machine\":[\"Pentagon128\"],\"dev.SnapshotFile\":[\"pent\"]}"),
                json);
    }

    @Test
    void offersGoIntoTheMetadataPerExtension() throws IOException {
        Result result = compile(Map.of(
                "app.Exporter", ROLE,
                "p.Csv", """
                        package p;
                        @dev.crystal.plugins.api.Offers("Browse the game catalogue")
                        @dev.crystal.plugins.api.Offers(value = "Export as CSV", icon = "csv")
                        public class Csv implements app.Exporter { public String format() { return "csv"; } }
                        """));
        assertTrue(result.errors().isEmpty(), result.errors().toString());
        String json = Files.readString(out.resolve(METADATA)).replaceAll("\\s+", "");
        assertTrue(json.contains("\"offers\":[{\"text\":\"Browsethegamecatalogue\",\"icon\":\"\"},"
                + "{\"text\":\"ExportasCSV\",\"icon\":\"csv\"}]"), json);
    }

    @Test
    void anIncrementalCompilationKeepsWhatItDidNotRecompile() throws IOException {
        compile(Map.of(
                "dev.Equipment", "package dev; @dev.crystal.plugins.api.RoleInterface public interface Equipment { }",
                "dev.DeskEquipment",
                "package dev; @dev.crystal.plugins.api.RoleInterface public interface DeskEquipment { }",
                "dev.Beeper", "package dev; public class Beeper implements Equipment { }",
                "dev.Tape", "package dev; public class Tape implements Equipment { }"));
        // The IDE recompiles only the new file.
        Result second = compile(Map.of(
                "dev.WhatGameThisIs",
                "package dev; @dev.crystal.plugins.api.RoleInterface public interface WhatGameThisIs { }",
                "dev.Guesser", "package dev; public class Guesser implements WhatGameThisIs { }"));
        assertEquals(List.of(), second.errors());

        assertEquals(List.of("dev.DeskEquipment", "dev.Equipment", "dev.WhatGameThisIs"), lines(out.resolve(ROLES)));
        assertEquals(List.of("dev.Beeper", "dev.Guesser", "dev.Tape"), lines(out.resolve(EXTENSIONS)));
        assertEquals(List.of("dev.Beeper", "dev.Tape"), lines(out.resolve("META-INF/services/dev.Equipment")));
        assertTrue(Files.readString(out.resolve(METADATA)).contains("dev.Beeper"));

        // A class deleted since drops out.
        Files.delete(out.resolve("dev/Tape.class"));
        compile(Map.of("dev.Other", "package dev; public class Other { }", "dev.Guesser",
                "package dev; public class Guesser implements WhatGameThisIs { }"));
        assertEquals(List.of("dev.Beeper", "dev.Guesser"), lines(out.resolve(EXTENSIONS)));
    }

    private static final String ROLES = "META-INF/crystal/roles.idx";
    private static final String EXTENSIONS = "META-INF/extensions.idx";
    private static final String METADATA = "META-INF/plugin-metadata.json";

    private static List<String> lines(Path file) throws IOException {
        return Files.readAllLines(file).stream().filter(l -> !l.startsWith("#") && !l.isBlank()).toList();
    }

    private record Result(List<String> errors, List<String> notes, List<String> warnings) {
    }

    private Result compile(Map<String, String> sources) {
        return compile(sources, new RoleProcessor());
    }

    private Result compile(Map<String, String> sources, javax.annotation.processing.Processor... processors) {
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        DiagnosticCollector<JavaFileObject> diagnostics = new DiagnosticCollector<>();
        try (StandardJavaFileManager files = javac.getStandardFileManager(diagnostics, null, StandardCharsets.UTF_8)) {
            List<JavaFileObject> units = new ArrayList<>();
            sources.forEach((name, code) -> units.add(new SimpleJavaFileObject(
                    URI.create("string:///" + name.replace('.', '/') + ".java"), JavaFileObject.Kind.SOURCE) {
                @Override
                public CharSequence getCharContent(boolean ignoreEncodingErrors) {
                    return code;
                }
            }));
            List<String> options = List.of("--release", "21", "-proc:full", "-d", out.toString(),
                    // The output is on the class path, as in an IDE's incremental compilation.
                    "-cp", System.getProperty("java.class.path") + java.io.File.pathSeparator + out);
            JavaCompiler.CompilationTask task = javac.getTask(null, files, diagnostics, options, null, units);
            task.setProcessors(List.of(processors));
            task.call();
        } catch (IOException e) {
            throw new AssertionError(e);
        }
        return new Result(messages(diagnostics, Diagnostic.Kind.ERROR), messages(diagnostics, Diagnostic.Kind.NOTE),
                messages(diagnostics, Diagnostic.Kind.WARNING));
    }

    private static List<String> messages(DiagnosticCollector<JavaFileObject> diagnostics, Diagnostic.Kind kind) {
        return diagnostics.getDiagnostics().stream()
                .filter(d -> d.getKind() == kind)
                .map(d -> d.getMessage(null))
                .toList();
    }
}
